"""Render native Claude Code and Codex agent profiles from the engineering catalog."""

import argparse
import json
import sys
import tomllib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CLAUDE_DIR = ROOT / ".claude" / "agents"
CODEX_DIR = ROOT / ".codex" / "agents"
READ_TOOLS = "Read, Grep, Glob"
CLAUDE_TOOLS = {
    "inspect": READ_TOOLS,
    "research": READ_TOOLS + ", WebSearch, WebFetch",
    "build": READ_TOOLS + ", Edit, Write, Bash",
    "docs": READ_TOOLS + ", Edit, Write",
}
# A comment in both formats, so the agent never sees it: inside the YAML
# frontmatter for Claude, at the top of the TOML for Codex. It is also the
# ownership marker for updating and retiring profiles.
MARKER = "# Generated by scripts/generate_agents.py"
HEADER = f"{MARKER} from engineering/. Edit the source there and regenerate; direct edits are overwritten."


def profiles():
    source = ROOT / "engineering"
    mappings = tomllib.loads((source / "model-mappings.toml").read_text(encoding="utf-8"))
    roles = {path.stem: path for path in (source / "agents").glob("*.md")}
    if roles.keys() != mappings.keys():
        raise ValueError(f"Unpaired roles or mappings: {sorted(roles.keys() ^ mappings.keys())}")

    outputs = {}
    for name, path in sorted(roles.items()):
        heading, description, instructions = path.read_text(encoding="utf-8").strip().split("\n\n", 2)
        if heading != f"# {name}" or "\n" in description or not instructions.strip():
            raise ValueError(f"Expected a role heading, a one-line description and instructions in {path}")
        mapping = mappings[name]
        claude_model, claude_effort = mapping["claude"]
        codex_model, codex_effort = mapping["codex"]
        tools = CLAUDE_TOOLS[mapping["tools"]]
        body = f"{description}\n\n{instructions}"
        outputs[CLAUDE_DIR / f"{name}.md"] = (
            f"---\n{HEADER}\nname: {name}\ndescription: {json.dumps(description, ensure_ascii=False)}\n"
            f"model: {claude_model}\neffort: {claude_effort}\ntools: {tools}\n---\n\n{body}\n"
        )
        # Keep the TOML prompt readable while escaping quotes and literal backslashes.
        escaped_body = "\n".join(
            json.dumps(line, ensure_ascii=False)[1:-1] for line in body.split("\n")
        )
        outputs[CODEX_DIR / f"{name}.toml"] = (
            f'{HEADER}\nname = "{name}"\ndescription = {json.dumps(description, ensure_ascii=False)}\n'
            f'model = "{codex_model}"\nmodel_reasoning_effort = "{codex_effort}"\n\n'
            f'developer_instructions = """\n{escaped_body}"""\n'
        )
        parsed = tomllib.loads(outputs[CODEX_DIR / f"{name}.toml"])
        if parsed["developer_instructions"] != body:
            raise ValueError(f"Instructions failed to round-trip for {name}")
    return outputs


def is_generated_profile(path):
    if path.is_symlink() or not path.is_file():
        return False
    with path.open("rb") as profile:
        first = profile.readline().rstrip(b"\r\n")
        if path.suffix == ".md":
            return first == b"---" and profile.readline().rstrip(b"\r\n") == HEADER.encode()
        return first == HEADER.encode()


def orphans(outputs):
    """Generated profiles whose role is no longer in the catalog.

    A removed or renamed role would otherwise stay loaded by both CLIs. Only
    files carrying the marker count: these directories are also where a
    hand-written profile would live, and the generator does not own those.
    """
    found = []
    for directory, pattern in ((CLAUDE_DIR, "*.md"), (CODEX_DIR, "*.toml")):
        for path in sorted(directory.glob(pattern)):
            if path not in outputs and is_generated_profile(path):
                found.append(path)
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report stale, missing or orphaned profiles")
    args = parser.parse_args()
    outputs = profiles()
    updates = {}
    conflicts = False
    for path, content in outputs.items():
        if is_generated_profile(path):
            if path.read_text(encoding="utf-8") == content:
                continue
        elif path.is_symlink() or path.exists():
            print(f"Profile path already in use: {path.relative_to(ROOT)}", file=sys.stderr)
            conflicts = True
            continue
        updates[path] = content

    retired = orphans(outputs)
    if args.check:
        for path in retired:
            print(f"Orphaned profile: {path.relative_to(ROOT)}", file=sys.stderr)
        for path in updates:
            print(f"Needs regeneration: {path.relative_to(ROOT)}", file=sys.stderr)
    if conflicts or (args.check and (retired or updates)):
        return 1

    for path, content in updates.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    for path in retired:
        path.unlink()
        print(f"Removed orphaned profile: {path.relative_to(ROOT)}")
    print(f"{len(outputs)} native profiles are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
